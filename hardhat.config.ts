function sepoliaAccounts(): string[] | { mnemonic: string } {
  const pk = process.env.PRIVATE_KEY?.trim();
  if (pk) {
    return [pk.startsWith("0x") ? pk : `0x${pk}`];
  }
  return { mnemonic: MNEMONIC };
}

